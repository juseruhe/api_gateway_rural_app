const express = require("express");
const cors = require("cors");
const helmet = require("helmet");
const morgan = require("morgan");

const gatewayRoutes = require("./routes/gateway.routes");
const errorMiddleware = require("./middleware/error.middleware");

const app = express();

/*
|--------------------------------------------------------------------------
| Seguridad
|--------------------------------------------------------------------------
*/

app.use(
    helmet()
);

/*
|--------------------------------------------------------------------------
| CORS
|--------------------------------------------------------------------------
*/

app.use(
    cors({
        origin: "*"
    })
);

/*
|--------------------------------------------------------------------------
| Logs
|--------------------------------------------------------------------------
*/

app.use(
    morgan("combined")
);

/*
|--------------------------------------------------------------------------
| Body
|--------------------------------------------------------------------------
*/

app.use(
    express.json({
        limit: "2mb"
    })
);

app.use(
    express.urlencoded({
        extended: true,
        limit: "2mb"
    })
);

/*
|--------------------------------------------------------------------------
| Health Check
|--------------------------------------------------------------------------
*/

app.get("/health", (req, res) => {

    res.status(200).json({
        success: true,
        service: "api-gateway",
        status: "UP"
    });

});

/*
|--------------------------------------------------------------------------
| Gateway Routes
|--------------------------------------------------------------------------
*/

app.use(
    gatewayRoutes
);

/*
|--------------------------------------------------------------------------
| 404
|--------------------------------------------------------------------------
*/

app.use((req, res) => {

    res.status(404).json({
        success: false,
        message: "Ruta no encontrada",
        path: req.originalUrl
    });

});

/*
|--------------------------------------------------------------------------
| Error Handler
|--------------------------------------------------------------------------
*/

app.use(
    errorMiddleware
);

module.exports = app;